Rails.application.routes.draw do
  root "portal#home"
  get "/healthz", to: "portal#health"
  post "/register", to: "portal#register"
  post "/login", to: "portal#login"
  post "/logout", to: "portal#logout"
  get "/records", to: "portal#records"
  post "/records", to: "portal#create_record"
  post "/records/:id/update", to: "portal#update_record"
  post "/records/:id/delete", to: "portal#delete_record"
  get "/documents", to: "portal#documents"
  post "/documents", to: "portal#upload"
  get "/documents/:id", to: "portal#download"
  get "/reports", to: "portal#reports"
  get "/reports/:id", to: "portal#report"
  post "/reports", to: "portal#queue_report"
end
